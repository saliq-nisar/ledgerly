// Extracts `// #region name` … `// #endregion` blocks from the library's
// type-checked examples into src/content/snippets.generated.ts, so every code
// sample on the website is real, compiling code. Runs before dev/build.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const EXAMPLES = join(process.cwd(), "packages", "payments", "examples");
const OUT = join(process.cwd(), "src", "content", "snippets.generated.ts");

// Example files import the package source; show the published import paths instead.
const IMPORT_REWRITES = [
  [/(["'])(?:\.\.\/)+src\/adapters\/web\.js\1/g, '"@ledgerly/payments/web"'],
  [/(["'])(?:\.\.\/)+src\/index\.js\1/g, '"@ledgerly/payments"'],
  [/(["'])\.\/payments\.js\1/g, '"@/lib/payments"'],
  [/(["'])\.\/01-minimal\.js\1/g, '"./payments"'],
];

function* walk(dir) {
  for (const entry of readdirSync(dir).sort()) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) yield* walk(path);
    else if (entry.endsWith(".ts")) yield path;
  }
}

function dedent(lines) {
  const indents = lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length);
  const min = Math.min(...indents);
  return lines.map((l) => l.slice(min)).join("\n").trimEnd();
}

const snippets = {};
for (const file of walk(EXAMPLES)) {
  const id = relative(EXAMPLES, file).split(sep).join("/").replace(/\.ts$/, "");
  const lines = readFileSync(file, "utf8").split(/\r?\n/);
  let current = null;
  let buffer = [];
  for (const line of lines) {
    const start = line.match(/^\s*\/\/ #region (\S+)/);
    const end = /^\s*\/\/ #endregion/.test(line);
    if (start) {
      if (current) throw new Error(`${id}: nested #region ${start[1]}`);
      current = start[1];
      buffer = [];
    } else if (end) {
      if (!current) throw new Error(`${id}: #endregion without #region`);
      let code = dedent(buffer);
      for (const [pattern, replacement] of IMPORT_REWRITES) code = code.replace(pattern, replacement);
      snippets[`${id}#${current}`] = code;
      current = null;
    } else if (current) {
      buffer.push(line);
    }
  }
  if (current) throw new Error(`${id}: unterminated #region ${current}`);
}

const body = `// AUTO-GENERATED by scripts/extract-snippets.mjs from packages/payments/examples. Do not edit.
export const SNIPPETS = ${JSON.stringify(snippets, null, 2)} as const;

export type SnippetId = keyof typeof SNIPPETS;
`;
writeFileSync(OUT, body);
console.log(`✓ Extracted ${Object.keys(snippets).length} snippets from examples`);
